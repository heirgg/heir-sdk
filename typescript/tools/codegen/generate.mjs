// Writes src/generated/*.ts from ../spec. `--check` fails instead of writing when the committed output is out of date,
// so CI catches a spec change that was not regenerated. Nothing else in src/ is generated.
import {readFile, writeFile} from "node:fs/promises";
import {resolve, dirname} from "node:path";
import {fileURLToPath} from "node:url";
import openapiTS, {astToString} from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const spec = name => resolve(here, "../../../spec", name);
const out = name => resolve(here, "../../src/generated", name);
const check = process.argv.includes("--check");
const header = "// Generated by `npm run generate` from ../../spec. Do not edit by hand.\n\n";

const documents = [
  {file: "public-openapi.json", module: "public.ts"},
  {file: "stat-submission-openapi.json", module: "stats.ts"}
];
let stale = [];
for (const document of documents) {
  const json = JSON.parse(await readFile(spec(document.file), "utf8"));
  const ast = await openapiTS(json, {
    // An unspecified object is unknown, not `Record<string, never>`.
    emptyObjectsUnknown: true,
    // A field with a default is still one the caller may leave out; the API fills it in.
    defaultNonNullable: false
  });
  const text = header + astToString(ast);
  const target = out(document.module);
  const committed = await readFile(target, "utf8").catch(() => "");
  if (check) { if (committed !== text) stale.push(document.module); }
  else { await writeFile(target, text); console.log(`Wrote ${target}`); }
}
if (check) {
  if (stale.length) { console.error(`Out of date: ${stale.join(", ")}. Run \`npm run generate\` and commit the result.`); process.exit(1); }
  console.log("Generated types are up to date.");
}
